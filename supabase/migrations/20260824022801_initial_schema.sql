-- Direct messaging
CREATE TABLE public.conversaciones (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vol_id UUID NOT NULL REFERENCES public.vols(id),
    -- these are referencing the same thing?
    responsable_id UUID NOT NULL REFERENCES public.perfiles(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (vol_id, responsable_id)
);

CREATE TABLE public.mensajes (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id INT NOT NULL REFERENCES public.conversaciones(id) ON DELETE CASCADE,
    sender_id UUID NOT NULL REFERENCES public.perfiles(id),
    contenido TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    leido_at TIMESTAMPTZ,
    reply_to_id INT NULL REFERENCES public.mensajes(id),
    unsent_at TIMESTAMPTZ,
    edited_at TIMESTAMPTZ
);

CREATE TABLE public.mensajes_reportes (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id INT NOT NULL REFERENCES public.mensajes(id) ON DELETE CASCADE,
    reportado_por UUID NOT NULL REFERENCES public.perfiles(id),
    motivo VARCHAR NOT NULL CHECK (motivo IN ('inapropiado', 'acoso', 'spam', 'otro')),
    descripcion TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (mensaje_id, reportado_por)
);

