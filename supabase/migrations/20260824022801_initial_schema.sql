-- Servicios and centros
CREATE TABLE public.servicios_centro (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centro_id INT NOT NULL REFERENCES public.centros(id) ON DELETE CASCADE,
    nombre VARCHAR NOT NULL,
    turno VARCHAR NOT NULL CHECK (turno IN ('manana', 'mediodia', 'tarde')),
    horario VARCHAR NOT NULL
);

CREATE TABLE public.servicios_centro_dias (
    servicio_id INT NOT NULL REFERENCES public.servicios_centro(id) ON DELETE CASCADE,
    dia VARCHAR NOT NULL CHECK (dia IN ('lunes', 'martes', 'miercoles', 'jueves', 'viernes', 'sabado', 'domingo')),
    PRIMARY KEY (servicio_id, dia)
);

-- Volunteer preferences and availability
CREATE TABLE public.voluntario_centro (
    vol_id UUID NOT NULL REFERENCES public.vols(id) ON DELETE CASCADE,
    centro_id INT NOT NULL REFERENCES public.centros(id) ON DELETE CASCADE,
    PRIMARY KEY (vol_id, centro_id)
);

CREATE TABLE public.disponibilidad_voluntario (
    vol_id UUID NOT NULL REFERENCES public.vols(id) ON DELETE CASCADE,
    dia VARCHAR NOT NULL CHECK (dia IN ('lunes', 'martes', 'miercoles', 'jueves', 'viernes', 'sabado', 'domingo')),
    bloque VARCHAR NOT NULL CHECK (bloque IN ('manana', 'mediodia', 'tarde')),
    PRIMARY KEY (vol_id, dia, bloque)
);

CREATE TABLE public.confirmacion_semanal (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vol_id UUID NOT NULL REFERENCES public.vols(id) ON DELETE CASCADE,
    centro_id INT REFERENCES public.centros(id) ON DELETE SET NULL,
    semana_inicio DATE NOT NULL,
    bloque VARCHAR NOT NULL CHECK (bloque IN ('manana', 'mediodia', 'tarde')),
    observaciones TEXT,
    validado BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (vol_id, semana_inicio, bloque)
);

CREATE TABLE public.confirmacion_dia (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    confirmacion_id INT NOT NULL REFERENCES public.confirmacion_semanal(id) ON DELETE CASCADE,
    dia VARCHAR NOT NULL CHECK (dia IN ('lunes', 'martes', 'miercoles', 'jueves', 
                                        'viernes', 'sabado', 'domingo')),
    estado VARCHAR NOT NULL CHECK (estado IN ('confirmado', 'asistio', 'falta')),
    UNIQUE (confirmacion_id, dia)
);

-- Comunicados
CREATE TABLE public.comunicados (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha DATE NOT NULL,
    titulo TEXT NOT NULL,
    contenido TEXT NOT NULL,
    tipo VARCHAR NOT NULL CHECK (tipo IN ('general', 'urgente', 'evento', 'logro')),
    autor VARCHAR NOT NULL,
    destinatario VARCHAR NOT NULL CHECK (destinatario IN ('todos', 'activos', 'inactivos', 'internacional', 'centro'))
);

CREATE TABLE public.comunicados_centro (
    comunicado_id INT NOT NULL REFERENCES public.comunicados(id) ON DELETE CASCADE,
    centro_id INT NOT NULL REFERENCES public.centros(id) ON DELETE CASCADE,
    PRIMARY KEY (comunicado_id, centro_id)
);

CREATE TABLE public.comunicado_canales (
    comunicado_id INT NOT NULL REFERENCES public.comunicados(id) ON DELETE CASCADE,
    canal VARCHAR NOT NULL CHECK (canal IN ('correo', 'whatsapp')),
    PRIMARY KEY (comunicado_id, canal)
);

-- Actividades and related tables
CREATE TABLE public.actividades (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha DATE NOT NULL,
  actividad TEXT NOT NULL,
  grupo_edad VARCHAR CHECK (grupo_edad IN ('pequeno', 'mediano', 'todo')),
  estado VARCHAR NOT NULL CHECK (estado IN ('pendiente', 'en_proceso', 'completado')),
  observaciones TEXT,
  tipo VARCHAR CHECK (tipo IN ('social', 'reunion', 'limpieza', 'construccion', 
                        'mantenimiento', 'huerto', 'jardineria', 'primeros_auxilios', 
                        'fraternizacion', 'nutricion'))  
);

CREATE TABLE public.actividades_centros (
    actividad_id INT NOT NULL REFERENCES public.actividades(id) ON DELETE CASCADE,
    centro_id INT NOT NULL REFERENCES public.centros(id) ON DELETE CASCADE,
    PRIMARY KEY (actividad_id, centro_id)
);

CREATE TABLE public.actividades_voluntarios (
    actividad_id INT NOT NULL REFERENCES public.actividades(id) ON DELETE CASCADE,
    vol_id UUID NOT NULL REFERENCES public.vols(id) ON DELETE CASCADE,
    rol VARCHAR NOT NULL CHECK (rol IN ('lider', 'apoyo', 'auxiliar', 
                                'educador', 'responsable')),
    PRIMARY KEY (actividad_id, vol_id)
);

CREATE TABLE public.actividades_materiales (
    actividad_id INT NOT NULL REFERENCES public.actividades(id) ON DELETE CASCADE,
    material VARCHAR NOT NULL,
    conseguido BOOLEAN NOT NULL,
    PRIMARY KEY (actividad_id, material)
);

